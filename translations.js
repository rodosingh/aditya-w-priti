  // Translate text nodes in place, retaining markup, focus, listeners, and form values.
  // Original copy is retained per node so switching back to English is lossless.
  function render(root) {
    if (!root || root.nodeType !== Node.ELEMENT_NODE || root.closest(excluded))
      return;
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
    while (walker.nextNode()) {
      const node = walker.currentNode;
      if (node.parentElement.closest(excluded)) continue;
      const previous = textSources.get(node);
      const original =
        previous?.rendered === node.data ? previous.original : node.data;
      const translated = translate(normalize(original));
      const rendered = original.replace(/\S[\s\S]*\S|\S/, () => translated);
      textSources.set(node, { original, rendered });
      if (node.data !== rendered) node.data = rendered;
    }
    for (const node of [
      root,
      ...root.querySelectorAll("[aria-label], [placeholder], [title], [alt]"),
    ]) {
      if (node.closest(excluded)) continue;
      const saved = attributeSources.get(node) || {};
      for (const attribute of attributes) {
        if (!node.hasAttribute(attribute)) continue;
        const current = node.getAttribute(attribute);
        const previous = saved[attribute];
        const original =
          previous?.rendered === current ? previous.original : current;
        const rendered = translate(original);
        saved[attribute] = { original, rendered };
        if (current !== rendered) node.setAttribute(attribute, rendered);
      }
      attributeSources.set(node, saved);
    }
  }

